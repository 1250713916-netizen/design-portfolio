const grid=document.getElementById("projectGrid");
const modal=document.getElementById("projectModal");
let modalOpenedByHistory=false;
let touchStartX=0,touchStartY=0,touchStartTime=0;

function imageMarkup(src,alt){
  return `<img src="${src}" alt="${alt}" loading="lazy" onerror="this.replaceWith(Object.assign(document.createElement('div'),{className:'image-fallback',textContent:'请检查图片路径：${src}'}))">`;
}

grid.innerHTML=projects.map((p,i)=>`
  <article class="project-card" data-index="${i}" tabindex="0" role="button" aria-label="查看${p.title}项目详情">
    <div class="cover">${imageMarkup(p.cover,p.title)}</div>
    <div class="project-meta">
      <span class="index">${p.id}</span><h3>${p.title}</h3><span class="cat">${p.category}</span>
    </div>
  </article>`).join("");

function openProject(i){
  const p=projects[i];
  if(!p)return;
  document.getElementById("modalNo").textContent=`${p.id} / PROJECT`;
  document.getElementById("modalTitle").textContent=p.title;
  document.getElementById("modalCategory").textContent=p.category;
  const cover=document.getElementById("modalCover");
  cover.src=p.cover;cover.alt=p.title;
  document.getElementById("modalMeta").innerHTML=`<span><strong>年份</strong>　${p.year}</span><span><strong>职责</strong>　${p.role}</span>`;
  document.getElementById("modalIntro").textContent=p.intro;
  document.getElementById("modalDetails").innerHTML=p.details.map((d,n)=>`
    <article class="detail-item">
      <div class="detail-image">${imageMarkup(d.image,`${p.title} ${d.title}`)}</div>
      <div class="detail-text"><h4>${String(n+1).padStart(2,"0")} / ${d.title}</h4><p>${d.text||""}</p></div>
    </article>`).join("");
  modal.classList.add("open");modal.setAttribute("aria-hidden","false");
  document.body.classList.add("lock");modal.scrollTop=0;
  if(!modalOpenedByHistory){history.pushState({portfolioProject:true},"","#project");modalOpenedByHistory=true;}
}
function closeProject(fromPopState=false){
  if(!modal.classList.contains("open"))return;
  modal.classList.remove("open");modal.setAttribute("aria-hidden","true");document.body.classList.remove("lock");
  if(modalOpenedByHistory&&!fromPopState){modalOpenedByHistory=false;history.back();}
  else modalOpenedByHistory=false;
}
grid.addEventListener("click",e=>{const card=e.target.closest(".project-card");if(card)openProject(Number(card.dataset.index));});
grid.addEventListener("keydown",e=>{if((e.key==="Enter"||e.key===" ")&&e.target.classList.contains("project-card")){e.preventDefault();openProject(Number(e.target.dataset.index));}});
document.getElementById("modalClose").addEventListener("click",()=>closeProject());
document.getElementById("modalNext").addEventListener("click",()=>closeProject());
window.addEventListener("popstate",()=>{if(modalOpenedByHistory)closeProject(true);});
document.addEventListener("keydown",e=>{if(e.key==="Escape")closeProject();});
modal.addEventListener("click",e=>{if(e.target===modal)closeProject();});
modal.addEventListener("touchstart",e=>{const t=e.changedTouches[0];touchStartX=t.clientX;touchStartY=t.clientY;touchStartTime=Date.now();},{passive:true});
modal.addEventListener("touchend",e=>{const t=e.changedTouches[0],dx=t.clientX-touchStartX,dy=t.clientY-touchStartY,dt=Date.now()-touchStartTime;if(dx < -80&&Math.abs(dx)>Math.abs(dy)*1.3&&dt<700)closeProject();},{passive:true});

