const nav=document.querySelector(".desktop-nav");
menuButton.addEventListener("click",()=>{
  const open=nav.style.display==="flex";
  nav.style.display=open?"":"flex";
  menuButton.setAttribute("aria-expanded",String(!open));
  if(!open){nav.style.position="absolute";nav.style.right="5vw";nav.style.top="52px";nav.style.padding="16px 20px";nav.style.background="#e9e9e5";nav.style.flexDirection="column";nav.style.gap="18px";}
});
nav.querySelectorAll("a").forEach(a=>a.addEventListener("click",()=>{if(window.innerWidth<=700){nav.style.display="";menuButton.setAttribute("aria-expanded","false");}}));
